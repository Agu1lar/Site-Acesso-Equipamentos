import { createHmac, timingSafeEqual } from 'node:crypto';
import * as z from 'zod';
import type { ChatProInboundEvent } from '@/lib/chatpro-webhook';
import { phoneMatchKey } from '@/lib/lead-contact';

const contactSchema = z.object({ phone_number: z.string().nullable().optional() });
const conversationSchema = z.object({
  id: z.number(),
  inbox_id: z.number(),
  updated_at: z.number().optional(),
  meta: z.object({
    sender: contactSchema,
    assignee: z.object({ id: z.number() }).nullable().optional(),
    assignee_type: z.string().nullable().optional(),
    team: z.object({ id: z.number() }).nullable().optional(),
  }),
  messages: z.array(z.object({ id: z.number(), status: z.string().optional() })).optional(),
});
const payloadSchema = z.object({
  event: z.string(),
  account: z.object({ id: z.literal(3) }),
  id: z.number(),
  inbox: z.object({ id: z.number() }).optional(),
  inbox_id: z.number().optional(),
  conversation: conversationSchema.optional(),
  meta: conversationSchema.shape.meta.optional(),
  updated_at: z.number().optional(),
  changed_attributes: z.array(z.record(z.string(), z.unknown())).optional(),
  message_type: z.string().optional(),
  private: z.boolean().optional(),
  content: z.string().nullable().optional(),
  created_at: z.union([z.string(), z.number()]).optional(),
  status: z.string().optional(),
  content_attributes: z.object({ external_error: z.string().nullable().optional() }).optional(),
  attachments: z
    .array(
      z.object({
        file_type: z.string(),
        data_url: z.url().optional(),
        extension: z.string().nullable().optional(),
      }),
    )
    .optional(),
});

/** Verifies the signature generated by Chatwoot Webhooks::Trigger before parsing the body. */
export function verifyAcessoChatSignature(input: {
  body: string;
  timestamp: string | null;
  signature: string | null;
  secret: string;
  now?: number;
}) {
  if (
    !input.timestamp ||
    !/^\d{10}$/.test(input.timestamp) ||
    !input.signature?.match(/^sha256=[a-f0-9]{64}$/)
  ) {
    return false;
  }
  if (Math.abs((input.now ?? Date.now()) / 1000 - Number(input.timestamp)) > 300) {
    return false;
  }
  const expected = createHmac('sha256', input.secret)
    .update(`${input.timestamp}.${input.body}`)
    .digest();
  return timingSafeEqual(expected, Buffer.from(input.signature.slice(7), 'hex'));
}

/** Adapts the live WhatsApp inbox to the site's existing lead and attendance pipeline. */
export function parseAcessoChatWebhook(payload: unknown): ChatProInboundEvent | null {
  const parsed = payloadSchema.safeParse(payload);
  if (!parsed.success) {
    return null;
  }
  const root = parsed.data;
  const isMessage = root.event === 'message_created' || root.event === 'message_updated';
  const conversation = isMessage ? root.conversation : conversationSchema.safeParse(root).data;
  if (!conversation || conversation.inbox_id !== 2) {
    return null;
  }
  const phoneKey = phoneMatchKey(conversation.meta.sender.phone_number ?? '');
  if (!phoneKey) {
    return null;
  }
  const assigned =
    root.event === 'conversation_updated' &&
    root.changed_attributes?.some((change) => 'assignee_id' in change) &&
    conversation.meta.assignee_type === 'User' &&
    conversation.meta.assignee;
  if (!isMessage && !assigned) {
    return null;
  }
  if (
    isMessage &&
    (root.private !== false || !['incoming', 'outgoing'].includes(root.message_type ?? ''))
  ) {
    return null;
  }
  if (root.event === 'message_updated' && root.message_type !== 'outgoing') {
    return null;
  }
  const createdAt =
    typeof root.created_at === 'number' ? root.created_at * 1000 : (root.created_at ?? '');
  const date = isMessage ? new Date(createdAt) : new Date((root.updated_at ?? 0) * 1000);
  if (Number.isNaN(date.getTime()) || date.getTime() === 0) {
    return null;
  }
  const status =
    root.status ?? conversation.messages?.find((message) => message.id === root.id)?.status;
  const statusCode: Record<string, number> = { sent: 0, delivered: 1, read: 2, failed: 3 };
  const attachment = root.attachments?.[0];
  return {
    event: assigned
      ? 'assigned_session'
      : root.message_type === 'incoming'
        ? 'received_message'
        : 'sent_message',
    phoneKey,
    fromMe: root.message_type !== 'incoming',
    messagePreview: isMessage ? (root.content?.slice(0, 2000) ?? null) : null,
    eventAt: date,
    externalId: `chatwoot:3:${isMessage ? 'message' : 'conversation'}:${root.id}`,
    sessionId: `chatwoot:3:${conversation.id}`,
    departmentId: conversation.meta.team ? String(conversation.meta.team.id) : null,
    assigneeId: conversation.meta.assignee ? String(conversation.meta.assignee.id) : null,
    deliveryStatus: status ? (statusCode[status] ?? null) : null,
    deliveryError: root.content_attributes?.external_error ?? null,
    media: {
      mediaType: attachment?.file_type ?? null,
      mediaUrl: attachment?.data_url ?? null,
      mediaFilename: null,
      mediaMimetype: null,
    },
  };
}
